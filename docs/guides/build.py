def shots(*items):
    """items: (filename, caption, kind) where kind is 'phone' or 'wide'."""
    phones = [i for i in items if i[2] == 'phone']
    wides = [i for i in items if i[2] == 'wide']
    out = ''
    for f, c, _ in wides:
        s = img(f)
        if s: out += f'<figure class="wide"><img src="{s}"><figcaption>{c}</figcaption></figure>'
    if phones:
        out += '<div class="shots">' + ''.join(
            f'<figure class="phone"><img src="{img(f)}"><figcaption>{c}</figcaption></figure>' for f, c, _ in phones if img(f)) + '</div>'
    return out


