def img(name, width=None):
    path = os.path.join(SHOTS, name)
    if not os.path.exists(path):
        return ''
    im = Image.open(path).convert('RGB')
    im.thumbnail((1400, 1800))
    buf = io.BytesIO(); im.save(buf, 'JPEG', quality=78, optimize=True)
    return 'data:image/jpeg;base64,' + base64.b64encode(buf.getvalue()).decode()


def font(n):
    return 'data:font/woff2;base64,' + base64.b64encode(open(os.path.join(FONT, n), 'rb').read()).decode()


def logo():
    for n in sorted(os.listdir(LOGO)):
        if n.lower().endswith(('.png', '.jpg', '.svg')) and 'favicon' not in n:
            mime = 'image/svg+xml' if n.endswith('.svg') else 'image/png'
            return f'data:{mime};base64,' + base64.b64encode(open(os.path.join(LOGO, n), 'rb').read()).decode()
    return ''


