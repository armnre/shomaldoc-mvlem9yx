#!/usr/bin/env python3
"""Generate server/db/schema.sql and server/src/meta.json from .zite/db.ts.

Run from repo root:  python3 server/scripts/gen-schema.py
Re-run whenever the data model changes.
"""
import json, re, pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
src = (ROOT / '.zite/db.ts').read_text()

# accessor -> SDK table name, and display name -> SDK table name
clients = re.findall(r"^\s+(\w+): createTableClient<\w+, \w+>\('(\w+)'\), // \"([^\"]+)\"", src, re.M)
sdk_by_accessor = {a: s for a, s, _ in clients}
link_tables = {}
for name, a, b in re.findall(r'//\s+"(\w+)" — columns: "(\w+)", "(\w+)"', src):
    link_tables[frozenset([a[:-2], b[:-2]])] = (name, a, b)

lc = lambda s: s[0].lower() + s[1:]
tables = {}
for sdk_accessor, sdk in sdk_by_accessor.items():
    m = re.search(r'export type ' + sdk + r'RecordType = \{(.*?)\n\};', src, re.S)
    body = m.group(1)
    fields = {}
    comment = ''
    for line in body.split('\n'):
        line = line.strip()
        if line.startswith('/**'):
            comment = line
            continue
        fm = re.match(r'(\w+)\??: (.+);$', line)
        if not fm:
            continue
        fname, ftype = fm.groups()
        if fname == 'id':
            comment = ''
            continue
        lk = re.search(r'Links to (\w+) \(', comment)
        if lk:
            target = sdk_by_accessor[lk.group(1)]
            name, a, b = link_tables[frozenset([lc(sdk), lc(target)])]
            self_col = a if a == lc(sdk) + 'Id' else b
            other_col = b if self_col == a else a
            fields[fname] = {'kind': 'link', 'table': name, 'self': self_col, 'other': other_col, 'target': target}
        elif 'Read-only' in comment and 'created' in comment.lower():
            fields[fname] = {'kind': 'created'}
        elif 'Date+time' in comment:
            fields[fname] = {'kind': 'datetime'}
        elif 'Date-only' in comment:
            fields[fname] = {'kind': 'date'}
        elif ftype == 'ZiteAttachment[]':
            fields[fname] = {'kind': 'attachments'}
        elif ftype.endswith('[]') or ftype.startswith('Record<'):
            fields[fname] = {'kind': 'json'}
        elif ftype == 'number':
            fields[fname] = {'kind': 'number'}
        elif ftype == 'boolean':
            fields[fname] = {'kind': 'boolean'}
        else:
            fields[fname] = {'kind': 'text'}
        comment = ''
    tables[sdk] = {'accessor': sdk_accessor, 'fields': fields}

PG = {'text': 'text', 'number': 'double precision', 'boolean': 'boolean', 'datetime': 'timestamptz',
      'date': 'date', 'json': 'jsonb', 'attachments': 'jsonb', 'created': 'timestamptz NOT NULL DEFAULT now()'}
out = ['-- Generated by server/scripts/gen-schema.py — do not edit by hand.',
       'CREATE EXTENSION IF NOT EXISTS pgcrypto;', '']
for sdk, t in tables.items():
    cols = ['  id uuid PRIMARY KEY DEFAULT gen_random_uuid()',
            '  created_at timestamptz NOT NULL DEFAULT now()',
            '  updated_at timestamptz NOT NULL DEFAULT now()']
    for f, d in t['fields'].items():
        if d['kind'] != 'link':
            cols.append(f'  "{f}" {PG[d["kind"]]}')
    out.append(f'CREATE TABLE IF NOT EXISTS "{sdk}" (\n' + ',\n'.join(cols) + '\n);')
    for f, d in t['fields'].items():
        if d['kind'] != 'link':
            out.append(f'ALTER TABLE "{sdk}" ADD COLUMN IF NOT EXISTS "{f}" {PG[d["kind"]]};')
    out.append('')
seen = set()
for sdk, t in tables.items():
    for d in t['fields'].values():
        if d['kind'] == 'link' and d['table'] not in seen:
            seen.add(d['table'])
            a_tab = sdk if d['self'] == lc(sdk) + 'Id' else d['target']
            b_tab = d['target'] if a_tab == sdk else sdk
            out.append(f'''CREATE TABLE IF NOT EXISTS "{d['table']}" (
  "{d['self']}" uuid NOT NULL REFERENCES "{sdk}"(id) ON DELETE CASCADE,
  "{d['other']}" uuid NOT NULL REFERENCES "{d['target']}"(id) ON DELETE CASCADE,
  PRIMARY KEY ("{d['self']}", "{d['other']}")
);
CREATE INDEX IF NOT EXISTS "{d['table']}_{d['other']}_idx" ON "{d['table']}"("{d['other']}");''')
# Helpful indexes
for idx in ['"Theses"("status")', '"Theses"("studentId")', '"Theses"("supervisorId")', '"Profiles"("username")',
            '"Sessions"("tokenHash")', '"Notifications"("profileId")', '"Reviews"("reviewerId")']:
    tab, col = idx.split('(', 1)
    col = col.rstrip(')').strip('"')
    if col in tables[tab.strip('"')]['fields']:
        out.append(f'CREATE INDEX IF NOT EXISTS "{tab.strip(chr(34))}_{col}_idx" ON {idx};')

(ROOT / 'server/db').mkdir(parents=True, exist_ok=True)
(ROOT / 'server/db/schema.sql').write_text('\n'.join(out) + '\n')
(ROOT / 'server/src').mkdir(parents=True, exist_ok=True)
(ROOT / 'server/src/meta.json').write_text(json.dumps(tables, ensure_ascii=False, indent=1))
print(f'{len(tables)} tables, {len(seen)} link tables')
